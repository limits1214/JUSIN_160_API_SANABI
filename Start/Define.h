inline void BmpRender(
	HDC dsthDC,
	int dstX, int dstY,
	int dstWidth, int dstHeight,
	HDC srchDC,
	int srcX, int srcY,
	int srcWidth, int srcHeight
	)
{
	GdiTransparentBlt(dsthDC,				
		dstX,	// 복사 받을 공간의 LEFT	
		dstY,				// 복사 받을 공간의 TOP
		dstWidth,			// 복사 받을 공간의 가로 
		dstHeight,			// 복사 받을 공간의 세로 
		srchDC,				// 복사 할 DC
		srcX,					// 복사할 이미지의 LEFT, TOP
		srcY,
		srcWidth,		// 복사할 이미지의 가로, 세로
		srcHeight,
		RGB(255, 0, 255)
	);
}

inline void BmpPlgRender(
	HDC dsthDC,
	int dstX, int dstY,
	int dstWidth, int dstHeight,
	HDC srchDC,
	int srcX, int srcY,
	int srcWidth, int srcHeight,

	POINT* points,
	HDC plgDC,
	HDC resetDC
)
{
	PlgBlt(plgDC,
		points,
		srchDC,
		0, 0,
		srcWidth,
		srcHeight,
		NULL, NULL, NULL);

	GdiTransparentBlt(dsthDC,
		dstX,	// 복사 받을 공간의 LEFT	
		dstY,				// 복사 받을 공간의 TOP
		dstWidth,			// 복사 받을 공간의 가로 
		dstHeight,			// 복사 받을 공간의 세로 
		plgDC,				// 복사 할 DC
		srcX,					// 복사할 이미지의 LEFT, TOP
		srcY,
		srcWidth,		// 복사할 이미지의 가로, 세로
		srcHeight,
		RGB(255, 0, 255)
	);

	BitBlt(plgDC,
		0, 0,
		srcWidth,
		srcHeight,
		resetDC,
		0, 0, SRCCOPY);
}

